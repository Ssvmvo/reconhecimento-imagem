def is_prime(n):
    if n <= 1:
        return False
    if n <= 3:
        return True
    if n % 2 == 0:
        return False
    
    i = 3
    while i * i <= n:
        if n % i == 0:
            return False
        i += 2
    
    return True


numero = int(input("Digite um número: "))
if is_prime(numero):
    print("É primo")
else:
    print("Não é primo")